"""
ci_gate.py — Enterprise CI/CD Quality Gate & PR Merge Blocker.

Enforces Federal Reserve & institutional software quality gates on LLM prompt/model PRs:
  1. Minimum overall pass rate (default: >= 90%)
  2. Zero regressions on CRITICAL severity probes (hard fail if any critical probe drops)
  3. Zero unredacted PII leaks in output
  4. Max allowed probe score degradation (threshold: delta < -0.05)

Emits formatted Markdown for GitHub Actions Job Summaries ($GITHUB_STEP_SUMMARY) and PR comments.
Exits with 0 (Gate Passed) or 1 (Gate Blocked).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

# Safe UTF-8 console output for Windows / cross-platform terminals
if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
if sys.stderr and hasattr(sys.stderr, "reconfigure"):
    try:
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

from reporter.report_generator import EvalRunReport, ProbeResult, regression_diff, RegressionEntry


@dataclass
class GatePolicy:
    min_pass_rate: float = 0.90
    max_regressed_probes: int = 1
    block_on_critical_regression: bool = True
    block_on_pii_leak: bool = True
    regression_threshold: float = 0.05


@dataclass
class GateResult:
    passed: bool
    policy: GatePolicy
    pass_rate: float
    total_probes: int
    blocking_reasons: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    regression_entries: list[RegressionEntry] = field(default_factory=list)

    def render_markdown(self) -> str:
        status_icon = "🟢 GATE PASSED — MERGE ALLOWED" if self.passed else "🔴 GATE FAILED — MERGE BLOCKED"
        border_color = "#10b981" if self.passed else "#ef4444"

        lines = [
            f"# CI/CD LLM Evaluation Quality Gate",
            f"",
            f"### **Status: {status_icon}**",
            f"",
            f"| Metric | Target | Actual | Status |",
            f"|---|---|---|---|",
            f"| Overall Pass Rate | &ge; {self.policy.min_pass_rate * 100:.1f}% | {self.pass_rate * 100:.1f}% | {'✅' if self.pass_rate >= self.policy.min_pass_rate else '❌'} |",
            f"| Regressed Probes | &le; {self.policy.max_regressed_probes} | {sum(1 for e in self.regression_entries if e.status == 'REGRESSED')} | {'✅' if sum(1 for e in self.regression_entries if e.status == 'REGRESSED') <= self.policy.max_regressed_probes else '❌'} |",
            f"| Total Probes Evaluated | — | {self.total_probes} | ℹ️ |",
            f"",
        ]

        if self.blocking_reasons:
            lines.append("## ❌ Blocking Violations:")
            for reason in self.blocking_reasons:
                lines.append(f"- **[BLOCK]** {reason}")
            lines.append("")

        if self.warnings:
            lines.append("## ⚠️ Warnings:")
            for warn in self.warnings:
                lines.append(f"- {warn}")
            lines.append("")

        if self.regression_entries:
            lines.append("## Probe Regression Matrix vs Baseline")
            lines.append("")
            lines.append("| Probe ID | Baseline Score | Candidate Score | Delta | Status |")
            lines.append("|---|---|---|---|---|")
            for e in self.regression_entries:
                status_symbol = {"REGRESSED": "🔴", "IMPROVED": "🟢", "STABLE": "⚪", "NEW": "🆕", "MISSING": "❓"}.get(e.status, "")
                lines.append(f"| `{e.probe_id}` | {e.old_score:.4f} | {e.new_score:.4f} | {e.delta:+.4f} | {status_symbol} {e.status} |")
            lines.append("")

        lines.append("---")
        lines.append("*Generated by LLM Eval Harness Enterprise CI/CD Gate*")
        return "\n".join(lines)


def _load_report(path: str | Path) -> EvalRunReport:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    results = [ProbeResult(**r) for r in data.get("results", [])]
    return EvalRunReport(
        run_id=data.get("run_id", "unknown"),
        timestamp=data.get("timestamp", ""),
        model=data.get("model", "unknown"),
        total_probes=data.get("total_probes", len(results)),
        passed=data.get("passed", sum(1 for r in results if r.passed)),
        failed=data.get("failed", sum(1 for r in results if not r.passed)),
        pass_rate=data.get("pass_rate", 0.0),
        avg_local_score=data.get("avg_local_score", 0.0),
        avg_judge_score=data.get("avg_judge_score", 0.0),
        results=results,
        metadata=data.get("metadata", {}),
    )


def evaluate_gate(
    candidate: EvalRunReport,
    baseline: EvalRunReport | None = None,
    policy: GatePolicy | None = None,
) -> GateResult:
    """Evaluate candidate report against quality gate policy and baseline."""
    pol = policy or GatePolicy()
    blocking: list[str] = []
    warnings: list[str] = []

    # 1. Pass rate check
    if candidate.pass_rate < pol.min_pass_rate:
        blocking.append(
            f"Pass rate ({candidate.pass_rate * 100:.1f}%) is below minimum threshold ({pol.min_pass_rate * 100:.1f}%)"
        )

    # 2. PII leak check
    for r in candidate.results:
        if r.category == "pii_compliance" and r.pii_detected:
            if not r.passed and pol.block_on_pii_leak:
                blocking.append(f"Unredacted PII exposure detected on probe `{r.probe_id}`")

    # 3. Critical failure check
    critical_fails = [r.probe_id for r in candidate.results if not r.passed and r.severity == "CRITICAL"]
    if critical_fails:
        blocking.append(f"Failed CRITICAL severity probe(s): {critical_fails}")

    # 4. Regression diff against baseline
    entries: list[RegressionEntry] = []
    if baseline is not None:
        entries = regression_diff(baseline, candidate, threshold=pol.regression_threshold)
        regressed = [e for e in entries if e.status == "REGRESSED"]

        # Check critical regressions
        base_map = {r.probe_id: r for r in baseline.results}
        for reg in regressed:
            base_probe = base_map.get(reg.probe_id)
            if base_probe and base_probe.severity == "CRITICAL" and pol.block_on_critical_regression:
                blocking.append(
                    f"CRITICAL probe `{reg.probe_id}` regressed from {reg.old_score:.4f} to {reg.new_score:.4f} (delta: {reg.delta:+.4f})"
                )

        if len(regressed) > pol.max_regressed_probes:
            blocking.append(
                f"Too many regressed probes: {len(regressed)} probes regressed (max allowed: {pol.max_regressed_probes})"
            )
        elif regressed:
            warnings.append(f"{len(regressed)} non-critical probe(s) regressed slightly: {[e.probe_id for e in regressed]}")

    passed = len(blocking) == 0
    return GateResult(
        passed=passed,
        policy=pol,
        pass_rate=candidate.pass_rate,
        total_probes=candidate.total_probes,
        blocking_reasons=blocking,
        warnings=warnings,
        regression_entries=entries,
    )


def main():
    parser = argparse.ArgumentParser(description="LLM Eval Harness — CI/CD Quality Gate")
    parser.add_argument("candidate_json", help="Path to current run evaluation JSON")
    parser.add_argument("--baseline", default=None, help="Path to baseline evaluation JSON")
    parser.add_argument("--min-pass-rate", type=float, default=0.90, help="Minimum required pass rate (0.0 to 1.0)")
    parser.add_argument("--max-regressed", type=int, default=1, help="Max allowed regressed probes")
    parser.add_argument("--output-markdown", default=None, help="Path to write output markdown")
    args = parser.parse_args()

    candidate = _load_report(args.candidate_json)
    baseline = _load_report(args.baseline) if args.baseline and Path(args.baseline).exists() else None

    policy = GatePolicy(
        min_pass_rate=args.min_pass_rate,
        max_regressed_probes=args.max_regressed,
    )

    result = evaluate_gate(candidate, baseline, policy)
    md = result.render_markdown()

    print("\n" + md + "\n")

    if args.output_markdown:
        Path(args.output_markdown).write_text(md, encoding="utf-8")

    # Write to GitHub Actions summary if running in CI
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_path:
        with open(summary_path, "a", encoding="utf-8") as f:
            f.write("\n" + md + "\n")

    if not result.passed:
        logger_error = f"CI Quality Gate FAILED with {len(result.blocking_reasons)} violation(s)."
        print(f"\n[ERROR] {logger_error}", file=sys.stderr)
        sys.exit(1)
    else:
        print("\n[SUCCESS] CI Quality Gate PASSED.", file=sys.stdout)
        sys.exit(0)


if __name__ == "__main__":
    main()
