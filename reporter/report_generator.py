"""
report_generator.py — Markdown + JSON report generator for eval runs.

Produces:
  - Per-probe breakdown table
  - Aggregate statistics (pass rate, avg scores)
  - Regression diff vs baseline
  - JSON machine-readable output
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------

@dataclass
class ProbeResult:
    probe_id: str
    category: str
    local_score: float
    judge_score: float | None
    composite: float
    passed: bool
    flags: list[str] = field(default_factory=list)
    pii_detected: bool = False
    severity: str = "MEDIUM"
    latency_ms: float = 0.0
    input_text: str = ""
    output_text: str = ""


@dataclass
class EvalRunReport:
    run_id: str
    timestamp: str
    model: str
    total_probes: int
    passed: int
    failed: int
    pass_rate: float
    avg_local_score: float
    avg_judge_score: float
    results: list[ProbeResult] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def build(cls, results: list[ProbeResult], model: str = "unknown", run_id: str | None = None) -> "EvalRunReport":
        passed = sum(1 for r in results if r.passed)
        failed = len(results) - passed
        local_scores = [r.local_score for r in results]
        judge_scores = [r.judge_score for r in results if r.judge_score is not None]

        return cls(
            run_id=run_id or datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ"),
            timestamp=datetime.now(timezone.utc).isoformat(),
            model=model,
            total_probes=len(results),
            passed=passed,
            failed=failed,
            pass_rate=round(passed / len(results), 4) if results else 0.0,
            avg_local_score=round(sum(local_scores) / len(local_scores), 4) if local_scores else 0.0,
            avg_judge_score=round(sum(judge_scores) / len(judge_scores), 4) if judge_scores else 0.0,
            results=results,
        )


# ---------------------------------------------------------------------------
# Markdown renderer
# ---------------------------------------------------------------------------

def _status_emoji(passed: bool) -> str:
    return "✅" if passed else "❌"


def render_markdown(report: EvalRunReport) -> str:
    lines: list[str] = []

    lines.append(f"# LLM Eval Harness — Run Report")
    lines.append(f"")
    lines.append(f"**Run ID:** `{report.run_id}`  ")
    lines.append(f"**Timestamp:** {report.timestamp}  ")
    lines.append(f"**Model:** `{report.model}`  ")
    lines.append(f"")
    lines.append(f"## Summary")
    lines.append(f"")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Total Probes | {report.total_probes} |")
    lines.append(f"| Passed | {report.passed} |")
    lines.append(f"| Failed | {report.failed} |")
    lines.append(f"| Pass Rate | {report.pass_rate:.1%} |")
    lines.append(f"| Avg Local Score | {report.avg_local_score:.4f} |")
    lines.append(f"| Avg Judge Score | {report.avg_judge_score:.4f} |")
    lines.append(f"")
    lines.append(f"## Per-Probe Breakdown")
    lines.append(f"")
    lines.append(f"| # | Probe ID | Category | Local | Judge | Composite | PII | Flags | Status |")
    lines.append(f"|---|----------|----------|-------|-------|-----------|-----|-------|--------|")

    for r in report.results:
        judge_str = f"{r.judge_score:.3f}" if r.judge_score is not None else "—"
        pii_str = "⚠️" if r.pii_detected else "—"
        flags_str = ", ".join(r.flags) if r.flags else "—"
        lines.append(
            f"| | {r.probe_id} | {r.category} | {r.local_score:.3f} | {judge_str} | "
            f"{r.composite:.3f} | {pii_str} | {flags_str} | {_status_emoji(r.passed)} |"
        )

    lines.append("")
    lines.append("---")
    lines.append("*Generated by LLM Eval Harness*")

    return "\n".join(lines)


def render_json(report: EvalRunReport) -> str:
    return json.dumps(asdict(report), indent=2)


# ---------------------------------------------------------------------------
# Regression diff
# ---------------------------------------------------------------------------

@dataclass
class RegressionEntry:
    probe_id: str
    old_score: float
    new_score: float
    delta: float
    status: str   # IMPROVED | REGRESSED | STABLE | NEW | MISSING


def regression_diff(
    baseline: EvalRunReport,
    current: EvalRunReport,
    threshold: float = 0.05,
) -> list[RegressionEntry]:
    """
    Compare current run against baseline. Returns list of RegressionEntry.
    A probe is REGRESSED if delta < -threshold on CRITICAL/HIGH probes.
    """
    baseline_map = {r.probe_id: r for r in baseline.results}
    current_map = {r.probe_id: r for r in current.results}

    entries: list[RegressionEntry] = []

    all_ids = set(baseline_map) | set(current_map)
    for pid in sorted(all_ids):
        old = baseline_map.get(pid)
        new = current_map.get(pid)

        if old is None:
            entries.append(RegressionEntry(pid, 0.0, new.composite, new.composite, "NEW"))  # type: ignore[union-attr]
        elif new is None:
            entries.append(RegressionEntry(pid, old.composite, 0.0, -old.composite, "MISSING"))
        else:
            delta = new.composite - old.composite
            if delta < -threshold:
                status = "REGRESSED"
            elif delta > threshold:
                status = "IMPROVED"
            else:
                status = "STABLE"
            entries.append(RegressionEntry(pid, old.composite, new.composite, round(delta, 4), status))

    return entries


def render_regression_markdown(entries: list[RegressionEntry]) -> str:
    lines = [
        "# Regression Diff Report",
        "",
        "| Probe ID | Old Score | New Score | Delta | Status |",
        "|----------|-----------|-----------|-------|--------|",
    ]
    for e in entries:
        delta_str = f"{e.delta:+.4f}"
        status_icon = {"REGRESSED": "🔴", "IMPROVED": "🟢", "STABLE": "⚪", "NEW": "🆕", "MISSING": "❓"}.get(e.status, "")
        lines.append(
            f"| {e.probe_id} | {e.old_score:.4f} | {e.new_score:.4f} | {delta_str} | {status_icon} {e.status} |"
        )
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# File I/O helpers
# ---------------------------------------------------------------------------

def save_report(report: EvalRunReport, output_dir: str | Path = "eval_history") -> dict[str, Path]:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    json_path = out / f"{report.run_id}.json"
    md_path = out / f"{report.run_id}.md"

    json_path.write_text(render_json(report), encoding="utf-8")
    md_path.write_text(render_markdown(report), encoding="utf-8")

    return {"json": json_path, "markdown": md_path}
