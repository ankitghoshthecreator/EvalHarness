"""
ab_comparator.py — Prompt version A/B comparison.

Runs two prompt templates against the same probe bank and produces a diff:
  - Which probes flipped PASS → FAIL or FAIL → PASS
  - Aggregate score delta per version
  - Winner declaration
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from typing import Callable

# Safe UTF-8 console output for Windows / cross-platform terminals
if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
if sys.stderr and hasattr(sys.stderr, "reconfigure"):
    try:
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

from reporter.report_generator import EvalRunReport, ProbeResult


@dataclass
class ProbeFlip:
    probe_id: str
    flip: str          # "PASS→FAIL" | "FAIL→PASS" | "STABLE_PASS" | "STABLE_FAIL"
    score_a: float
    score_b: float
    delta: float


@dataclass
class ABReport:
    version_a: str
    version_b: str
    winner: str        # "A" | "B" | "TIE"
    avg_delta: float   # B - A (positive = B wins)
    pass_rate_a: float
    pass_rate_b: float
    flips: list[ProbeFlip] = field(default_factory=list)

    def summary(self) -> str:
        lines = [
            f"A/B Comparison: {self.version_a} vs {self.version_b}",
            f"  Pass rate A: {self.pass_rate_a:.1%}  |  Pass rate B: {self.pass_rate_b:.1%}",
            f"  Avg score delta (B - A): {self.avg_delta:+.4f}",
            f"  Winner: {self.winner}",
            f"  Flips: {sum(1 for f in self.flips if '→' in f.flip)} probe(s) changed status",
        ]
        return "\n".join(lines)


def compare(
    report_a: EvalRunReport,
    report_b: EvalRunReport,
    version_a: str | None = None,
    version_b: str | None = None,
) -> ABReport:
    """
    Compare two eval run reports (A and B).

    Args:
        report_a: Results from prompt version A.
        report_b: Results from prompt version B.
        version_a: Label for version A (defaults to report_a.run_id).
        version_b: Label for version B.

    Returns:
        ABReport with flips and winner.
    """
    va = version_a or report_a.run_id
    vb = version_b or report_b.run_id

    map_a = {r.probe_id: r for r in report_a.results}
    map_b = {r.probe_id: r for r in report_b.results}

    all_ids = sorted(set(map_a) & set(map_b))
    flips: list[ProbeFlip] = []
    deltas: list[float] = []

    for pid in all_ids:
        ra = map_a[pid]
        rb = map_b[pid]
        delta = rb.composite - ra.composite
        deltas.append(delta)

        if ra.passed and not rb.passed:
            flip = "PASS→FAIL"
        elif not ra.passed and rb.passed:
            flip = "FAIL→PASS"
        elif ra.passed and rb.passed:
            flip = "STABLE_PASS"
        else:
            flip = "STABLE_FAIL"

        flips.append(ProbeFlip(pid, flip, ra.composite, rb.composite, round(delta, 4)))

    avg_delta = round(sum(deltas) / len(deltas), 4) if deltas else 0.0

    if avg_delta > 0.01:
        winner = "B"
    elif avg_delta < -0.01:
        winner = "A"
    else:
        winner = "TIE"

    return ABReport(
        version_a=va,
        version_b=vb,
        winner=winner,
        avg_delta=avg_delta,
        pass_rate_a=report_a.pass_rate,
        pass_rate_b=report_b.pass_rate,
        flips=flips,
    )


def render_ab_markdown(ab: ABReport) -> str:
    lines = [
        f"# A/B Prompt Comparison: `{ab.version_a}` vs `{ab.version_b}`",
        "",
        f"**Winner: {ab.winner}**  ",
        f"Pass Rate A: {ab.pass_rate_a:.1%} | Pass Rate B: {ab.pass_rate_b:.1%}  ",
        f"Avg Score Delta (B − A): {ab.avg_delta:+.4f}",
        "",
        "## Probe-Level Results",
        "",
        "| Probe ID | Score A | Score B | Delta | Flip |",
        "|----------|---------|---------|-------|------|",
    ]
    flip_icons = {
        "PASS→FAIL": "🔴 PASS→FAIL",
        "FAIL→PASS": "🟢 FAIL→PASS",
        "STABLE_PASS": "⚪ STABLE PASS",
        "STABLE_FAIL": "⚫ STABLE FAIL",
    }
    for f in sorted(ab.flips, key=lambda x: abs(x.delta), reverse=True):
        lines.append(
            f"| {f.probe_id} | {f.score_a:.4f} | {f.score_b:.4f} | {f.delta:+.4f} | {flip_icons.get(f.flip, f.flip)} |"
        )
    lines.append("")
    lines.append("---")
    lines.append("*Generated by LLM Eval Harness A/B Comparator*")
    return "\n".join(lines)


def main():
    import argparse
    import json
    from pathlib import Path

    parser = argparse.ArgumentParser(description="LLM Eval Harness — A/B Comparator")
    parser.add_argument("report_a", help="Path to JSON report for version A")
    parser.add_argument("report_b", help="Path to JSON report for version B")
    parser.add_argument("--name-a", default=None, help="Label for version A")
    parser.add_argument("--name-b", default=None, help="Label for version B")
    parser.add_argument("--output", default=None, help="Optional markdown output file path")
    args = parser.parse_args()

    with open(args.report_a, encoding="utf-8") as f:
        data_a = json.load(f)
    with open(args.report_b, encoding="utf-8") as f:
        data_b = json.load(f)

    def _load_report(data: dict) -> EvalRunReport:
        results = [ProbeResult(**r) for r in data.get("results", [])]
        return EvalRunReport(
            run_id=data.get("run_id", "unknown"),
            timestamp=data.get("timestamp", ""),
            model=data.get("model", "unknown"),
            total_probes=data.get("total_probes", len(results)),
            passed=data.get("passed", sum(1 for r in results if r.passed)),
            failed=data.get("failed", sum(1 for r in results if not r.passed)),
            pass_rate=data.get("pass_rate", 0.0),
            avg_local_score=data.get("avg_local_score", 0.0),
            avg_judge_score=data.get("avg_judge_score", 0.0),
            results=results,
            metadata=data.get("metadata", {}),
        )

    rep_a = _load_report(data_a)
    rep_b = _load_report(data_b)

    ab = compare(rep_a, rep_b, version_a=args.name_a, version_b=args.name_b)
    md = render_ab_markdown(ab)
    print(md)

    if args.output:
        Path(args.output).write_text(md, encoding="utf-8")
        print(f"\nSaved A/B diff report to {args.output}")


if __name__ == "__main__":
    main()
